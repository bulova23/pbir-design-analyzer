import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const schemaPath = path.join(root, 'contracts', 'score-panel', 'v1', 'schema.json');
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
const generatedTs = `// GENERATED FILE - do not edit. Run npm run generate:contract.\nexport const GENERATED_PROTOCOL_VERSION = ${schema.properties.protocolVersion.const};\nexport const GENERATED_SCHEMA_VERSION = ${schema.properties.schemaVersion.const};\nexport const GENERATED_MUTATION_OPERATIONS = ['preview', 'apply', 'rollback'] as const;\nexport type GeneratedMutationOperation = typeof GENERATED_MUTATION_OPERATIONS[number];\n`;
const generatedCs = `// <auto-generated> GENERATED FILE - do not edit. Run npm run generate:contract. </auto-generated>\nnamespace PowerBIModelingService.RpcHost;\n\ninternal static class GeneratedScorePanelContract\n{\n    internal const int ProtocolVersion = ${schema.properties.protocolVersion.const};\n    internal const int SchemaVersion = ${schema.properties.schemaVersion.const};\n    internal static readonly IReadOnlySet<string> MutationOperations = new HashSet<string>(StringComparer.Ordinal) { "preview", "apply", "rollback" };\n}\n`;
const outputs = [
  [path.join(root, 'vscode-extension', 'src', 'generated', 'scorePanelContract.ts'), generatedTs],
  [path.join(root, 'service-dotnet', 'RpcHost', 'GeneratedScorePanelContract.g.cs'), generatedCs],
];
const check = process.argv.includes('--check');
const mismatches = [];
for (const [file, contents] of outputs) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) mismatches.push(path.relative(root, file));
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, contents);
  }
}
if (mismatches.length) {
  console.error(`Generated contract is stale: ${mismatches.join(', ')}`);
  process.exit(1);
}
console.log(`${check ? 'Generated contract freshness' : 'Generated contract'} passed.`);
